WITH RENTAL_BY_PERIOD AS (
    SELECT CAR_ID AS ID, COUNT(*) AS CNT
    FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY
    WHERE START_DATE >= '2022-08-01' AND START_DATE < "2022-11-1" 
    GROUP BY CAR_ID
    HAVING COUNT(*) >= 5
)
# SELECT * FROM RENTAL_BY_PERIOD
SELECT MONTH(START_DATE) AS MONTH, CAR_ID, COUNT(*) AS RECORDS
FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY
WHERE  START_DATE >= '2022-08-01' AND START_DATE < "2022-11-1" AND EXISTS (SELECT 1 FROM RENTAL_BY_PERIOD WHERE ID = CAR_ID)
GROUP BY MONTH, CAR_ID
ORDER BY MONTH ASC, CAR_ID DESC
;


